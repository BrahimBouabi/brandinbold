import type { CdpConnection } from '../cdp/connection'

interface CookieRecord {
  name: string
  value: string
  domain: string
  path: string
  expires?: number // seconds since epoch
  httpOnly?: boolean
  secure?: boolean
  sameSite?: 'Strict' | 'Lax' | 'None'
}

/** Export all cookies of a running profile browser (dedicated user-data-dir ⇒ they are all that profile's). */
export async function exportCookies(cdp: CdpConnection): Promise<CookieRecord[]> {
  const { cookies } = await cdp.send('Storage.getCookies', {})
  return (cookies as any[]).map((c) => ({
    name: c.name,
    value: c.value,
    domain: c.domain,
    path: c.path,
    expires: c.expires > 0 ? c.expires : undefined,
    httpOnly: c.httpOnly,
    secure: c.secure,
    sameSite: normalizeSameSite(c.sameSite)
  }))
}

export async function importCookies(cdp: CdpConnection, cookies: CookieRecord[]): Promise<number> {
  let n = 0
  for (const c of cookies) {
    const ok = await cdp
      .send('Network.setCookie', {
        name: c.name,
        value: c.value,
        domain: c.domain,
        path: c.path || '/',
        secure: !!c.secure,
        httpOnly: !!c.httpOnly,
        sameSite: mapSameSite(c.sameSite),
        ...(c.expires && c.expires > 0 ? { expires: c.expires } : {})
      })
      .catch(() => false)
    if (ok) n++
  }
  return n
}

function mapSameSite(s?: string): 'Strict' | 'Lax' | 'None' {
  if (s === 'Strict') return 'Strict'
  if (s === 'None') return 'None'
  return 'Lax'
}

function normalizeSameSite(s?: string): 'Strict' | 'Lax' | 'None' | undefined {
  if (s === 'Strict' || s === 'Lax' || s === 'None') return s
  return undefined
}

/** Netscape cookies.txt: # HttpOnly_ prefix and 7 tab-separated fields. */
export function toNetscapeFormat(cookies: CookieRecord[]): string {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Rea', '']
  for (const c of cookies) {
    const prefix = c.httpOnly ? '#HttpOnly_' : ''
    const includeSubdomains = c.domain.startsWith('.') ? 'TRUE' : 'FALSE'
    const expires = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0
    lines.push(
      [
        prefix + c.domain,
        includeSubdomains,
        c.path || '/',
        c.secure ? 'TRUE' : 'FALSE',
        String(expires),
        c.name,
        c.value
      ].join('\t')
    )
  }
  return lines.join('\n') + '\n'
}

export function parseNetscapeFormat(text: string): CookieRecord[] {
  const cookies: CookieRecord[] = []
  for (const line of text.split('\n')) {
    if (!line || line.startsWith('#') && !line.startsWith('#HttpOnly_')) continue
    let httpOnly = false
    let l = line
    if (l.startsWith('#HttpOnly_')) {
      httpOnly = true
      l = l.slice('#HttpOnly_'.length)
    }
    const parts = l.split('\t')
    if (parts.length < 7) continue
    const [domain, , path, secure, expires, name, value] = parts
    cookies.push({
      domain,
      path,
      name,
      value,
      secure: secure === 'TRUE',
      expires: parseInt(expires, 10) || undefined,
      httpOnly
    })
  }
  return cookies
}
